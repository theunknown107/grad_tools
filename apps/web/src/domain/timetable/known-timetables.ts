/**
 * Timetables the app already knows, verified entry by entry.
 *
 * When a student uploads one of these (as a photo, a Word file or a
 * spreadsheet), the app shows the stored, verified timetable instead of what
 * OCR or the parser managed to read: subject name, code, day, time, room and
 * faculty, exactly as the college printed them.
 *
 * WHAT IS STORED: the 5th-semester CSBS timetables, academic year 2026-27,
 * revision R0: sections V (A) and V (B) effective 12.09.2026 (checked against
 * the Word original, each grid cell and each section's subject table), and
 * section V (B) effective 01.10.2026 (checked against the printed sheet).
 *
 * WHEN IT IS USED: only when the reading shows a stored edition: the CSBS
 * department (by name, or by two of its own markers: `BCB…` course codes or
 * the CSBS-only course `MRMM`), a section printed as `V (A)` / `V (B)`, and
 * that edition's effective date. Any other edition (07.09.2026, V (A) of
 * 01.10.2026) or revision has different classes, so it is parsed as usual.
 */
import type { DocxTimetableSection } from './docx-timetable.js';
import type { DictionaryEntry, GridClass, ParsedTimetable, TimeSlot } from './timetable-import.js';
import type { Weekday } from './primitives.js';

/** One stored class. A null `code` is an hour that names no single course. */
function k(
  day: Weekday,
  start: string,
  end: string,
  printed: string,
  code: string | null,
  title: string | null,
  faculty: string | null,
  room: string | null,
  batch: string | null,
  spansSlots: number,
): GridClass {
  return {
    day,
    start,
    end,
    subjectCode: code,
    resolution: code === null ? 'activity' : 'declared',
    unresolvedReason: null,
    initials: printed,
    batch,
    room,
    spansSlots,
    sourceText: printed,
    title,
    faculty,
  };
}

function timetable(
  section: string,
  slots: readonly TimeSlot[],
  dictionary: readonly DictionaryEntry[],
  classes: readonly GridClass[],
  batches: readonly string[],
  effectiveFrom = '2026-09-12',
): ParsedTimetable {
  return {
    context: {
      className: `CSBS ${section}`,
      semester: 5,
      academicYear: '2026-27',
      revision: 'R0',
      effectiveFrom,
      room: null,
    },
    slots,
    dictionary,
    classes,
    batches,
    conflicts: [],
    coverage: {
      cellsFound: classes.length,
      cellsResolved: classes.length,
      slotsFound: slots.filter((slot) => !slot.isBreak).length,
      dictionaryEntries: dictionary.length,
      looksComplete: true,
    },
    warnings: [],
  };
}

/** An edition's date, tolerant of how OCR spaces and punctuates it: `12.09.2026`, `12. 09. 2026`, `12/9/2026`. */
const date = (day: number, month: number) =>
  new RegExp(String.raw`\b0?${day}\s*[./-]\s*0?${month}\s*[./-]\s*2026\b`);
/** A printed revision other than R0 means a different edition. */
const REVISION = /\(\s*R\s*(\d)\s*\)/i;
const SECTION_A = /\bV\s*[([]\s*A\s*[)\]]/;
const SECTION_B = /\bV\s*[([]\s*B\s*[)\]]/;
const CSBS_NAME = /business\s*system/i;
/** CSBS's own course codes, and MRMM (Marketing Research & Marketing Management), a CSBS-only course. */
const CSBS_MARK = /\bBCBL?\d{3}[A-Z]?\b|\bMRMM\b/g;

/**
 * The stored sections this reading is, in printed order; empty when it is not
 * a stored edition. `lines` is whatever the reader produced (OCR lines, a
 * Word file's or a spreadsheet's text), so the check works for every format.
 */
export function knownTimetables(
  lines: readonly { readonly text: string }[],
): DocxTimetableSection[] {
  const text = lines
    .map((line) => line.text)
    .join('\n')
    .replace(/\s+/g, ' ');
  const edition = EDITIONS.find((e) => e.date.test(text));
  if (edition === undefined) return [];
  const revision = REVISION.exec(text)?.[1];
  if (revision !== undefined && revision !== '0') return [];
  const csbs = CSBS_NAME.test(text) || new Set(text.match(CSBS_MARK) ?? []).size >= 2;
  if (!csbs) return [];

  const found: DocxTimetableSection[] = [];
  if (edition.a !== null && SECTION_A.test(text))
    found.push({ label: 'CSBS 5A', tableIndex: -1, timetable: edition.a });
  if (SECTION_B.test(text)) found.push({ label: 'CSBS 5B', tableIndex: -1, timetable: edition.b });
  return found;
}

